BLOCK_TMPL = f"""{BEGIN}
================================================================================
TARGETED VULN SWEEP (SIGNAL-DRIVEN, BOUNDED — not a blind scan)
================================================================================

Fire this the moment your own fingerprint/enumeration phase has a CONFIRMED
product on a {{{{TARGET}}}} surface — not before, and never on a bare target.
No confirmed product = NO sweep: a scanner with no product in hand is the
blind, minutes-long scan we refuse. One sweep per confirmed product per
host:port, then pivot straight to exploitation.

TECH PROFILE (this agent):
  nuclei tags : <TAGS>
  vulnx query : <VULNX>
Everything below is scoped to these. Never widen to a full CVE spray, never run
nuclei with no -tags, never drop the severity floor, never sweep a product this
agent does not own.

WALL-CLOCK BUDGET <= 90s for the whole sweep. Every command carries its own
timeout; if one burns its timeout twice, mark it FAILED_WITH_PROOF and move on.
The campaign never blocks on a scanner.

STEP 1 — vulnx first (cheapest, ~3s, and it tells you what nuclei can confirm).
Run it only once you have read a VERSION:
  darkmoon_execute_command(command="bash -lc 'timeout 45 vulnx search \\"<VULNX> <VERSION>\\" --limit 15 2>&1'")
Keep only the critical/high records whose AFFECTED version range the observed
version falls into. For each, read the detail (it prints whether a Nuclei
Template exists, plus EPSS / KEV):
  darkmoon_execute_command(command="bash -lc 'timeout 30 vulnx id <CVE> 2>&1'")

STEP 2 — nuclei, targeted to exactly what STEP 1 found (seconds, not minutes):
  - CVE with a non-destructive nuclei template -> confirm it precisely:
      darkmoon_execute_command(command="bash -lc 'nuclei -u {{{{TARGET}}}} -id <CVE> -timeout 8 -retries 1 -duc -nc -jsonl 2>/dev/null'")
    A matcher hit is CONFIRMED (template-matched): push it with the raw match.
  - CVE with NO template (memory corruption, logic RCE): do NOT exploit. The
    version match against the vendor advisory IS the proof -> status CONFIRMED
    (version-matched), severity = the advisory's, record the version evidence
    and the advisory URL.

STEP 3 — ONLY if you could not read a version at all, one broad but bounded
product pass (the fallback; kept high-signal so it stays fast). Nuclei's own
output is already one concise line per finding ([template-id] [proto]
[severity] url) — read it directly, keep stderr, never truncate it:
  darkmoon_execute_command(command="bash -lc 'nuclei -u {{{{TARGET}}}} -tags <TAGS> -severity critical,high -timeout 5 -retries 0 -rl 40 -c 25 -duc -nc 2>&1'")

NON-DESTRUCTIVE ALWAYS: detection / cve-check templates only. NEVER add
-tags intrusive,dos,fuzz,bruteforce and never a payload that can crash or
mutate the target. A record with no matchable version range -> UNCONFIRMED,
severity info; never push a CVE for a version the record does not cover.

SECONDARY TECH IS A SIGNAL, NOT YOUR JOB: if the fingerprint exposes a product
this agent does not own (a database banner, a reverse proxy, another CMS or
framework), do NOT scan it here — record it as a FACT so the orchestrator
dispatches the right agent. You sweep only <VULNX>.
{END}"""


def block_for(agent):
    tags, vulnx = TECH_PROFILES[agent]
    return BLOCK_TMPL.replace("<TAGS>", tags).replace("<VULNX>", vulnx)


def rw(path, fn):
    with open(path, "r", encoding="utf-8", newline="") as fh:
        text = fh.read()
    nl = "\r\n" if "\r\n" in text else "\n"
    new = fn(text.replace("\r\n", "\n"))
    if nl == "\r\n":
        new = new.replace("\n", "\r\n")
    if new != text:
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(new)
        return True
    return False


def inject_agent(agent):
    block = block_for(agent)

    def fn(text):
        if BEGIN in text:  # replace an older copy of the block in place
            head, rest = text.split(BEGIN, 1)
            tail = rest.split(END, 1)[1].lstrip("\n")
            return head + block + "\n" + tail
        lines = text.split("\n")
        try:
            i = next(n for n, l in enumerate(lines) if l.strip() == ANCHOR)
        except StopIteration:
            raise RuntimeError(f"{agent}: anchor {ANCHOR!r} not found")
        # the anchor heading is preceded by its own separator line
        at = i - 1 if lines[i - 1].startswith("====") else i
        return "\n".join(lines[:at]) + "\n" + block + "\n" + "\n".join(lines[at:])

    return fn


def main(argv):
    only = None
    if argv and argv[0] == "--only":
        only = argv[1]
        argv = argv[2:]
    if not argv:
        sys.exit(__doc__)
    agents = [only] if only else sorted(TECH_PROFILES)
    for repo in argv:
        d = os.path.join(repo, "conf", "agents")
        for a in agents:
            md = os.path.join(d, a + ".md")
            if not os.path.isfile(md):
                print(f"  SKIP (absent): {repo}/conf/agents/{a}.md")
                continue
            changed = rw(md, inject_agent(a))
            print(f"  {'updated' if changed else 'unchanged'}: {repo}/conf/agents/{a}.md")


if __name__ == "__main__":
    main(sys.argv[1:])
