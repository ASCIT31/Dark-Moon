"""
Darkmoon targeted-vuln-sweep injector.

Stamps one byte-identical, signal-driven scanner-dispatch block into every
web/service-facing sub-agent, parameterised by a single per-agent TECH PROFILE
line (nuclei tags + vulnx query for THAT agent's technology). It replaces the
old "same generic -tags exposure,misconfig,tech-detect for everyone" habit with
a bounded, product-targeted, version-first sweep that stays fast.

Doctrine (generalises the hand-tuned PHP RUNTIME CVE CHECK to the whole fleet):
  1. vulnx first, only once a VERSION is read (cheapest, ~3s, and it says
     whether a nuclei template even exists for each CVE).
  2. nuclei targeted to the CVEs vulnx returned (seconds, not minutes).
  3. a broad `-tags <product>` pass ONLY as the no-version fallback.
A CVE with no nuclei template (memory corruption, logic RCE) is proven by the
version match against the vendor advisory, never by exploiting it — same rule
as the PHP block, now for every product.

The block is delimited by markers, so re-running is idempotent and a newer copy
replaces an older one in place. Run it AFTER tools/agent-build/generate.py (the
spine generator does not know per-agent tech profiles), exactly like
php_runtime_cves.py. Guarded by tools/check-no-regression.sh.

Usage:
    python3 targeted_vuln_scan.py <repo> [<repo> ...]
    python3 targeted_vuln_scan.py --only wordpress <repo>   # single agent (test)
"""
