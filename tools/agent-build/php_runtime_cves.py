#!/usr/bin/env python3
"""
Inject the PHP RUNTIME CVE CHECK block into every PHP-family agent (php + the PHP
CMS/LMS/e-commerce agents) and a matching note into pentest.md's PHP signal.

Why: runtime CVEs sit BELOW the application. App/CMS modules never look at them
and nuclei misses them until a template ships. PHP2Shell (CVE-2026-109618 /
CVE-2026-109619, 2026-10-21) was missed this way in the lab (darkmoon-labs
labs/php2shell): the version was fingerprinted, reported as a mere disclosure.

The block is byte-identical in every agent and delimited by markers, so a new
runtime CVE is one edit here + a re-run. Newline-safe (keeps Front-API CRLF).
Idempotent.

Usage: python3 php_runtime_cves.py <repo> [<repo> ...]
"""
import os
import sys

AGENTS = ["php", "wordpress", "drupal", "joomla", "magento", "moodle", "prestashop"]
BEGIN = "<!-- darkmoon:php-runtime-cves BEGIN (generated by tools/agent-build/php_runtime_cves.py, edit there) -->"
END = "<!-- darkmoon:php-runtime-cves END -->"
ANCHOR = "SCANNER CONTROL BLOCK (NUCLEI / VULNX)"
SEP = "=" * 80

BLOCK = f"""{BEGIN}
{SEP}
PHP RUNTIME CVE CHECK (MANDATORY, NON-DESTRUCTIVE)
{SEP}

Runtime CVEs live below the application: application and CMS modules never see
them, and nuclei misses them until a template ships. Run this check ONCE per
PHP host:port, before the application modules, and push the result immediately.

1. FINGERPRINT THE RUNTIME (passive, bounded):
   darkmoon_execute_command(command="timeout 15 curl -sk -o /dev/null -D - {{{{TARGET}}}}/")
   Version sources, most trusted first:
     - X-Powered-By: PHP/X.Y.Z
     - Server header carrying PHP/X.Y.Z (e.g. "Apache/2.4.x (Debian) PHP/8.x.y")
     - a phpinfo() / site-health / admin "server info" page already found
     - a version string inside a PHP error or warning body
   Adversarial check before trusting it: request a second path that is served
   by PHP (a .php route, the login page) and confirm the same version. A reverse
   proxy or CDN can inject a stale header; if two PHP responses disagree, report
   the lower version as UNCONFIRMED and say why.
   No version visible: no finding from this block. Never infer the PHP version
   from the OS, the CMS version, or the absence of a header.

2. COMPARE WITH THE RUNTIME CVE TABLE (per branch, numeric compare):

   PHP2Shell: CVE-2026-109618 (out-of-memory corruption during request startup)
            + CVE-2026-109619 (stale request state, heap use-after-free)
     Disclosed 2026-10-21. Unauthenticated remote code execution, CVSS v4.0 9.2.
     Every SAPI serving web requests: mod_php (highest risk, triggers before
     application code runs), php-fpm, php-cgi, FrankenPHP, LiteSpeed.
     Fixed in 8.2.35, 8.3.36, 8.4.27, 8.5.12.
       8.2.x < 8.2.35, 8.3.x < 8.3.36, 8.4.x < 8.4.27, 8.5.x < 8.5.12  -> VULNERABLE
       8.1.x and older (end of life, no upstream fix)                  -> VULNERABLE,
         unless the version string carries a distribution or LTS build suffix
         (e.g. "8.1.2-1ubuntu2.20", "+deb12u3", "-1+0~2026") -> POTENTIALLY
         VULNERABLE: the vendor may have backported the fix. Severity high,
         and state in the description that the vendor advisory must be checked.
       At or above the fixed release of its branch                      -> NOT
         vulnerable: push NOTHING for these CVEs.

3. NEVER EXPLOIT. Both bugs are memory corruption with no trusted public PoC.
   Memory-exhaustion, oversized-body, multipart-flood, upload-progress race or
   fuzzing payloads can crash or corrupt the target's workers. Send none of
   them. The proof is the version evidence.

4. STATUS AND SEVERITY (explicit exception to the STATUS QUALIFICATION cap):
   a vendor advisory naming the exact observed version is the demonstrated
   impact. Status = CONFIRMED (version-matched), NEVER EXPLOITED. Severity =
   the advisory's severity (critical for PHP2Shell), cvss_score = 9.2. Only the
   inconsistent-header case of step 1 stays UNCONFIRMED.

5. PUSH one finding per host:port covering both CVEs:
   darkmoon_dashboard_push_finding(
     title="PHP runtime vulnerable to PHP2Shell unauthenticated RCE (CVE-2026-109618, CVE-2026-109619): PHP X.Y.Z",
     severity="critical", cvss_score=9.2, category="remote_code_execution",
     status="confirmed", cve="CVE-2026-109618, CVE-2026-109619",
     cvss_vector="CVSS:4.0 base score 9.2 (php.net advisory, 2026-10-21)",
     plugin_or_component="php X.Y.Z (<SAPI if known>)",
     endpoint="{{{{TARGET}}}}/",
     evidence_commands=<the curl commands of step 1>,
     raw_response=<the raw header lines carrying the version, both requests>,
     evidence_explanation="Version-matched against the php.net advisory; not exploited by design (memory corruption, no safe PoC).",
     remediation="Upgrade PHP to 8.2.35 / 8.3.36 / 8.4.27 / 8.5.12 or later (or the vendor backport for end-of-life branches) and restart every worker. Until then, exposure reduction only (php.net advisory): session.upload_progress.enabled=0 in php.ini or the FPM pool/server config (not .user.ini or ini_set); post_max_size=8M (32M if uploads are needed) with upload_max_filesize below it; request body, field and part limits at the web server or proxy (LimitRequestBody, client_max_body_size); on PHP 8.5 fatal_error_backtraces=0. Set expose_php=Off as hardening; hiding the version does not fix it.",
     ...)
   References for the description: https://www.php.net/archive/2026.php#2026-10-21-5,
   GHSA-w8hw-w9fx-j79w (CVE-2026-109618), GHSA-6wmf-4rv5-p3rp (CVE-2026-109619).

6. NEWER RUNTIME CVES: the table above is a snapshot. After step 2, run ONE
   bounded lookup:
   darkmoon_execute_command(command="timeout 60 vulnx search 'php remote code execution' --limit 20 2>&1")
   For a critical PHP-core CVE in the output that is NOT in the table, run
   `timeout 30 vulnx id <CVE> 2>&1`. Push it only if the record names fixed or
   affected versions that the observed version falls into (status confirmed,
   advisory severity). If the record gives no version range, push it as
   UNCONFIRMED, severity info: "runtime CVE to verify against PHP X.Y.Z".
   Never push a CVE for a version the record does not cover.
{END}
"""

PENTEST_NOTE = ("    - NOTE: every PHP-family agent (php, wordpress, drupal, joomla, magento, moodle, "
                "prestashop) also checks the PHP RUNTIME version against its runtime CVE table "
                "(PHP2Shell CVE-2026-109618/109619 and later). Pass the raw X-Powered-By / Server "
                "header line in CONTEXT PASS so the check runs even when the CMS hides it on later pages.")
PENTEST_AFTER = "DISPATCH: php"


def rw(path, fn):
    with open(path, "r", encoding="utf-8", newline="") as fh:
        text = fh.read()
    nl = "\r\n" if "\r\n" in text else "\n"
    new = fn(text.replace("\r\n", "\n"))
    if nl == "\r\n":
        new = new.replace("\n", "\r\n")
    if new != text:
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(new)
        return True
    return False


def inject_agent(text):
    if BEGIN in text:  # replace an older copy of the block
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        return head + BLOCK + "\n" + tail
    lines = text.split("\n")
    i = next(n for n, l in enumerate(lines) if l.strip() == ANCHOR)
    # the anchor heading is preceded by its own separator line
    at = i - 1 if lines[i - 1].startswith("====") else i
    return "\n".join(lines[:at]) + "\n" + BLOCK + "\n" + "\n".join(lines[at:])


def inject_pentest(text):
    if "PHP RUNTIME version against its runtime CVE table" in text:
        return text
    marker = "\n" + PENTEST_AFTER + "\n"
    assert marker in text, "pentest.md: 'DISPATCH: php' line not found"
    return text.replace(marker, marker[:-1] + "\n" + PENTEST_NOTE + "\n", 1)


def main(repos):
    for repo in repos:
        d = os.path.join(repo, "conf", "agents")
        for a in AGENTS:
            changed = rw(os.path.join(d, a + ".md"), inject_agent)
            print(f"  {'updated' if changed else 'unchanged'}: {repo}/conf/agents/{a}.md")
        changed = rw(os.path.join(d, "pentest.md"), inject_pentest)
        print(f"  {'updated' if changed else 'unchanged'}: {repo}/conf/agents/pentest.md")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
